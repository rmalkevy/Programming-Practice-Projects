// Дослід 4: пріоритет операцій. `==` зв'язує тісніше за `&`.
// Запуск: ./run.sh 04 2                 — НЕ збереться: -Werror робить попередження помилкою
//         NO_WERROR=1 ./run.sh 04 2     — збереться з попередженням; подивіться, що надрукує
// Lab 02, Теорія §3 · Notes 02, §4
#include "common.hpp"

int main(int argc, char* argv[]) {
    if (argc < 2) {
        std::cout << "usage: ./run.sh 04 <число>   наприклад: 2, 3, 6\n";
        return 1;
    }
    long x = 0;
    try {
        x = parse_number(argv[1]);
    } catch (const std::exception&) {
        std::cout << "не можу прочитати як число: " << argv[1] << '\n';
        return 1;
    }

    // Задумано: «x парне?» — молодший біт нульовий.
    std::cout << "x & 1 == 0     → " << (x & 1 == 0) << "    насправді це x & (1 == 0), тобто x & 0\n";
    std::cout << "(x & 1) == 0   → " << ((x & 1) == 0) << '\n';

    // Те саме з маскою: «біт 2 виставлений?»
    std::cout << "x & 4 == 4     → " << (x & 4 == 4) << "    насправді це x & (4 == 4), тобто x & 1\n";
    std::cout << "(x & 4) == 4   → " << ((x & 4) == 4) << '\n';
}
