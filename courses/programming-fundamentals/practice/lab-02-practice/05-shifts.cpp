// Дослід 5: зсуви. Куди дівається біт, що виїхав, і коли зсув — це UB.
// Запуск: ./run.sh 05 3     — зсув на 3
//         ./run.sh 05 31    — одиниця заїжджає в знаковий біт int
//         ./run.sh 05 32    — зсув на ширину типу: UBSan скаже своє
// Lab 02, Теорія §3 · Notes 02, §4
#include "common.hpp"

int main(int argc, char* argv[]) {
    if (argc < 2) {
        std::cout << "usage: ./run.sh 05 <на скільки зсунути>   наприклад: 3, 31, 32\n";
        return 1;
    }
    int n = 0;
    try {
        n = (int)parse_number(argv[1]);
    } catch (const std::exception&) {
        std::cout << "не можу прочитати як число: " << argv[1] << '\n';
        return 1;
    }

    // n приходить з командного рядка, тож компілятор не бачить його заздалегідь
    // і не може попередити. Ловить лише UBSan — під час запуску.
    std::cout << "int:       1  << " << n << " = " << (1 << n) << '\n';
    std::cout << "unsigned:  1u << " << n << " = " << (1u << n) << '\n';

    // Байт: біт, що виїхав за сьому позицію, — це і є прапорець C для SHL.
    std::uint8_t b = 0xC1;
    int wide = b << 1;                    // b спершу стає int, тож дев'ятий біт не губиться
    std::uint8_t kept = (std::uint8_t)wide;
    std::cout << "\nSHL байта " << bits(b) << ":\n";
    std::cout << "  b << 1 як int       = " << wide << "  (дев'ять бітів: 1 " << bits(kept) << ")\n";
    std::cout << "  у uint8_t лишається = " << bits(kept) << " = " << (int)kept << '\n';
    std::cout << "  C = (b >> 7) & 1    = " << ((b >> 7) & 1) << "  ← біт, що виїхав\n";

    // Зсув праворуч від'ємного числа: зверху заходять копії знакового біта.
    std::int8_t s = -8;
    std::uint8_t u = (std::uint8_t)s;     // ті самі біти
    std::cout << "\n>> 1 для тих самих бітів " << bits(u) << ":\n";
    std::cout << "  як int8_t  -8 >> 1  = " << bits((std::uint8_t)(s >> 1)) << " = " << (s >> 1)
              << "   ← зверху зайшла одиниця (знак)\n";
    std::cout << "  як uint8_t 248 >> 1 = " << bits((std::uint8_t)(u >> 1)) << " = " << (u >> 1)
              << "   ← зверху зайшов нуль\n";
}
